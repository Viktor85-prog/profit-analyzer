// -----------------------------------
// get sector
// -----------------------------------

export function getSector(ticker, assetType = "") {
  const normalized = normalizeTicker(ticker);

  if (assetType === "bonds") {
    return "Облигации";
  }

  return SECTOR_MAP[normalized] || "Прочее";
}
