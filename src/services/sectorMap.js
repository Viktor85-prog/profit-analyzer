// -----------------------------------
// normalize ticker
// -----------------------------------

export function normalizeTicker(ticker) {
  return String(ticker || "")
    .replace(/\/\d+$/, "")
    .replace(/_\d+$/, "")
    .trim()
    .toUpperCase();
}

